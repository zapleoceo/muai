from __future__ import annotations

import re
import unicodedata
from typing import Callable, NamedTuple

#: Языки наших созвонов. Всё прочее — сбой определителя, а не язык.
EXPECTED = ("ru", "uk", "en", "id")
#: Чем перепроверяем подозрительный кусок. Украинский под `ru` тоже даёт
#: кириллицу (замер выше), так что для проверки хватает одного прохода.
CHECK_WITH = "ru"
#: Доля кириллицы, начиная с которой речь считается не английской. Замеры
#: разведены далеко (0.00 против 0.99), порог посередине.
CYRILLIC_MIN = 0.5

_LETTER = re.compile(r"[^\W\d_]")


class Choice(NamedTuple):
    result: object
    found: str
    chosen: str
    reason: str


def language_of(result) -> str:
    """Язык из ответа пайплайна; форматы `ru` и `<|ru|>` оба бывают."""
    return (getattr(result, "language", "") or "").strip("<|> ")


def cyrillic_share(text: str) -> float:
    letters = _LETTER.findall(text)
    if not letters:
        return 0.0
    return sum(1 for c in letters if unicodedata.name(c, "").startswith("CYRILLIC")) / len(letters)


def choose(result, rerun: Callable[[str], object]) -> Choice:
    """Оставить ответ модели или заменить его перепроверкой с `CHECK_WITH`."""
    found = language_of(result)
    # Пустое поле — другая версия пайплайна, а не сбой: судить не по чему.
    if not found or (found in EXPECTED and found != "en"):
        return Choice(result, found, found, "модель")
    checked = rerun(CHECK_WITH)
    share = cyrillic_share(str(checked))
    if share >= CYRILLIC_MIN:
        return Choice(checked, found, CHECK_WITH, f"под {CHECK_WITH} кириллица {share:.2f}")
    if found == "en":
        return Choice(result, found, "en", f"под {CHECK_WITH} кириллица {share:.2f}")
    # Чужой язык и под `ru` не кириллица: речь латиницей, из наших это
    # английский. Прогон с `ru` не годится — на огрызке он переводит на
    # русский (замер выше), а у исходного ответа токен чужого языка.
    english = rerun("en")
    return Choice(english, found, "en", f"{found} не из {EXPECTED}, под {CHECK_WITH} "
                  f"кириллица {share:.2f}")

"""Выбор языка куска при `auto`: модели верим, но английскому — после проверки.

## Что случилось 24.09.2026

С 14:28 все созвоны пошли английским: на daily с 26-й минуты, на личках, на
вечернем звонке — целиком. Русская речь при этом не терялась, а ПЕРЕВОДИЛАСЬ:
«Слушай, я сегодня была на встрече» → «Listen, I was on a meeting». Так
whisper ведёт себя, когда решил, что язык куска `en`, — `task=transcribe` с
английским токеном на русском звуке и есть перевод. По событиям сервера доля
кириллицы в стенограммах 16–23.09 — 0.94…1.00 на всех 54 сессиях, 24.09 после
14:28 — 0.00…0.04 (кроме одного куска `ru` в 18:31). Перезапуск слушателя в
18:52 не помог: первый же кусок свежего пайплайна снова `en`.

Состояние между вызовами на CPU не залипает — проверено последовательностью
ru → en → ru → uk → шум → ru → тишина → тихий ru → «ага» → ru на одном
пайплайне: каждый кусок получил свой язык, `generation_config.language`
остался `None`. На NPU то же проверить не удалось: пока работает живой
слушатель, второй пайплайн на NPU не поднимается (`bad allocation`, без кэша —
падение процесса). Почему определитель на NPU весь день отвечал `en`, из
данных не видно: звук не хранится. Поэтому защита не гадает о причине, а
закрывает сам вред.

## Как защищаемся

Списка языков-кандидатов у `WhisperGenerationConfig` нет, а `scores` в ответе
при жадном поиске всегда 1.0 (замер) — сравнить варианты по уверенности модели
нельзя. Зато есть измеримый признак. Кусок, где модель сказала `en` или язык
не из ожидаемых (`is` 24.09), распознаётся ещё раз с `ru`, и решает письмо:

| звук                      | с токеном `ru` — доля кириллицы |
|---------------------------|---------------------------------|
| русская речь, 49 с        | 0.99                            |
| украинская, 7 с           | 1.00                            |
| английская, 57 с и 20 с   | 0.00 — whisper пишет английский как есть |
| английская, 4 с           | 0.00 и 1.00 — на огрызке бывает перевод |

Кириллица под `ru` — речь не английская, берём этот вариант. Нет её — звук и
правда английский, и первый вариант остаётся. Цена — второй проход, но только
на кусках, где модель сказала `en`: на русском созвоне его не бывает, пока
определитель здоров. Короткий английский огрызок может уйти русским
переводом — это сознательный размен: обратная ошибка (русский разговор
английским переводом) стоила целого дня стенограмм.
"""
from __future__ import annotations

import re
import unicodedata
from typing import Callable, NamedTuple

#: Языки наших созвонов. Всё прочее — сбой определителя, а не язык.
EXPECTED = ("ru", "uk", "en", "id")
#: Чем перепроверяем подозрительный кусок. Украинский под `ru` тоже даёт
#: кириллицу (замер выше), так что для проверки хватает одного прохода.
CHECK_WITH = "ru"
#: Доля кириллицы, начиная с которой речь считается не английской. Замеры
#: разведены далеко (0.00 против 0.99), порог посередине.
CYRILLIC_MIN = 0.5

_LETTER = re.compile(r"[^\W\d_]")


class Choice(NamedTuple):
    result: object
    found: str
    chosen: str
    reason: str


def language_of(result) -> str:
    """Язык из ответа пайплайна; форматы `ru` и `<|ru|>` оба бывают."""
    return (getattr(result, "language", "") or "").strip("<|> ")


def cyrillic_share(text: str) -> float:
    letters = _LETTER.findall(text)
    if not letters:
        return 0.0
    return sum(1 for c in letters if unicodedata.name(c, "").startswith("CYRILLIC")) / len(letters)


def choose(result, rerun: Callable[[str], object]) -> Choice:
    """Оставить ответ модели или заменить его перепроверкой с `CHECK_WITH`."""
    found = language_of(result)
    # Пустое поле — другая версия пайплайна, а не сбой: судить не по чему.
    if not found or (found in EXPECTED and found != "en"):
        return Choice(result, found, found, "модель")
    checked = rerun(CHECK_WITH)
    share = cyrillic_share(str(checked))
    if share >= CYRILLIC_MIN:
        return Choice(checked, found, CHECK_WITH, f"под {CHECK_WITH} кириллица {share:.2f}")
    if found == "en":
        return Choice(result, found, "en", f"под {CHECK_WITH} кириллица {share:.2f}")
    # Чужой язык, а под `ru` не кириллица: скорее всего английский. Берём
    # вариант с `ru` — на английском звуке он и остаётся английским (замер).
    return Choice(checked, found, CHECK_WITH, f"{found} не из {EXPECTED}")

"""Слушатель разговоров вокруг ноутбука. Клиент Vera, живёт только локально."""
import os

# OpenMP по умолчанию ждёт АКТИВНО: свободные воркеры крутятся в цикле, а не
# спят. Детектор речи (silero на ggml) зовут 62 раза в секунду — две дорожки по
# 31 кадру, — промежуток 16 мс, и воркеры уснуть не успевают: три ядра горят
# непрерывно даже в полной тишине, когда слушатель по замыслу почти ничего не
# делает. Поймано вживую: процесс набрал 162 минуты процессорного времени за 50
# минут работы.
#
# Замер на живом ноутбуке (8 ядер): по умолчанию 223% ядра, с PASSIVE — 5%.
# `OMP_NUM_THREADS=1` не помогает вовсе (270%): число потоков ggml задаёт сам,
# а жжёт именно активное ожидание. Распознавание при этом не медленнее:
# 20 секунд звука за 2.2с в обоих случаях.
#
# Ставится ДО любых импортов пакета: переменную читает vcomp140.dll в момент
# загрузки, то есть при первом импорте нативной библиотеки. `setdefault` —
# чтобы заданное снаружи значение осталось за старшим.
os.environ.setdefault("OMP_WAIT_POLICY", "PASSIVE")

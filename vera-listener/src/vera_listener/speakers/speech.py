"""Оставить в куске только речь — тишина внутри портит отпечаток.

Whisper отдаёт границы реплики с запасом: внутри 3.5 секунд может оказаться
полторы секунды слов и две секунды тишины. Модель голоса усредняет по ВСЕМУ
куску, поэтому тишина размывает отпечаток до неузнаваемости. Замер 16.09,
один и тот же голос, кусок всегда 3.5с — меняется только доля речи в нём:

    речи в куске     косинус со своим же голосом
      3.5с (чисто)             0.888
      2.5с                     0.704
      2.0с                     0.360
      1.5с                     0.239
      1.0с                     0.158

Ниже 0.45 — это меньше, чем у ЧУЖИХ голосов между собой. То есть кусок с
тишиной не просто хуже узнаётся: свой голос в нём выглядит более чужим, чем
посторонний человек. Отсюда и разваливались кластеры.

Вживую 16.09: клиент в созвоне дал восемь «собеседников» вместо одного —
сорок реплик в главном кластере и семь одиночек, и все семь оказались его же
короткими фразами («по форматированию», «камняный век и»). Порог в три
секунды, поставленный 04.09, это не ловил: он мерил длину КУСКА, а не длину
речи в нём.
"""
from __future__ import annotations

import numpy as np

from vera_listener.vad import FRAME_SAMPLES, SpeechDetector


def keep_speech(audio: np.ndarray) -> np.ndarray:
    """Моно float32 16 кГц → только те кадры, в которых есть речь.

    Детектор заводится свой на каждый вызов: у silero есть история, и кусок
    из середины разговора не должен наследовать состояние предыдущего.
    """
    count = len(audio) // FRAME_SAMPLES
    if count == 0:
        return audio[:0]

    detector = SpeechDetector()
    frames = audio[:count * FRAME_SAMPLES].reshape(count, FRAME_SAMPLES)
    pcm = np.clip(frames, -1.0, 1.0)
    pcm = (pcm * 32767.0).astype(np.int16)
    voiced = [i for i in range(count) if detector.is_speech(pcm[i].tobytes())]
    if not voiced:
        return audio[:0]
    return frames[voiced].reshape(-1)

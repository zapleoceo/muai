"""Склейка соседних сегментов whisper в цельную реплику.

Whisper режет одно предложение по запятым: «То есть я на такой тип вопроса,» /
«я просто думаю,» / «что надо не выводить диаграмму.» — три «реплики» вместо
одной. Замер по трём живым созвонам (события 483070, 483722, 483820, 6913
реплик): **25.4% короче четырёх слов**, медиана — 6 слов.

Беда не только в читаемости. Отпечаток голоса снимается только с куска, где
не меньше `features.MIN_VOICEPRINT_S` (3 с) речи, а обрывок столько не длится
почти никогда — отсюда имена всего у 14% реплик созвона. Склейка лечит обе
беды разом: длиннее текст — длиннее вырезка звука.

## Когда склеиваем

Оба условия вместе, и оба — собственный сигнал whisper «предложение не
кончилось»:

1. предыдущий кусок не кончается знаком конца (`.`, `!`, `?`, `…`);
2. зазор до следующего не больше `MERGE_GAP_S`.

Порог зазора нарочно почти нулевой. Разрезая предложение по запятой, whisper
ставит куски ВСТЫК: конец одного равен началу следующего, зазора нет вовсе.
0.2 с — это допуск на округление таймкодов, а не «короткая пауза»: пауза
смены говорящего в живом созвоне длиннее.

## Чем рискуем и почему порог такой

В групповом созвоне подряд идущие сегменты дорожки `system` принадлежат РАЗНЫМ
людям, и склейка тогда смешала бы два голоса в один отпечаток — это хуже
обрывков: обрывок остаётся безымянным, а смешанный отпечаток разъезжает
кластеры и портит уже накопленные имена.

Замер риска на тех же созвонах, по соседним репликам `system`, где имя знают
ОБЕ (132 пары): у 38 пар говорящие разные — смена собеседника между соседними
сегментами дело обычное, примерно каждая третья пара. Поэтому склейка не
опирается на одну лишь паузу: нужен ещё незакрытый знак конца, а сама пауза
допускается только в пределах ошибки округления.

Третий предохранитель — `MERGE_MAX_S`: цепочка склеек не растёт дальше 15 с.
Отпечатку 15 с хватает с запасом (порог — 3 с), а длинная цепочка — ровно тот
случай, где шанс задеть чужой голос копится с каждым звеном.
"""
from __future__ import annotations

from dataclasses import dataclass

#: Больше этого зазора — уже пауза, а не разрез предложения по запятой.
MERGE_GAP_S = 0.2

#: Потолок склеенной реплики. Отпечатку хватает трёх секунд, а каждое лишнее
#: звено цепочки — новый шанс прихватить чужой голос.
MERGE_MAX_S = 15.0

#: Знаки, которыми whisper закрывает законченную мысль.
SENTENCE_END = ".!?…"

#: Кавычки и скобки после точки: «…сроки.» закончена так же, как «…сроки».
_TRAILING = "\"'»)]“”"


@dataclass(frozen=True)
class Segment:
    """Одна распознанная реплика внутри куска.

    `at` и `end` — секунды от начала КУСКА, не сессии: смещение куска
    прибавляет вызывающий, он же один знает, где кусок стоит в разговоре.
    """

    at: float
    end: float
    text: str

    @property
    def duration(self) -> float:
        return max(0.0, self.end - self.at)


def looks_unfinished(text: str) -> bool:
    """Кончается ли реплика на полуслове — по знаку в конце, не по смыслу."""
    stripped = text.strip().rstrip(_TRAILING)
    return bool(stripped) and stripped[-1] not in SENTENCE_END


def merge_continuations(segments: list[Segment], *, gap_s: float = MERGE_GAP_S,
                        max_span_s: float = MERGE_MAX_S) -> list[Segment]:
    """Соседние куски одного предложения → одна реплика.

    Склеивает только подряд идущие сегменты ОДНОГО куска одной дорожки: ничего
    другого в списке и не бывает, а значит склейка не может свести речь разных
    дорожек.
    """
    merged: list[Segment] = []
    for segment in segments:
        previous = merged[-1] if merged else None
        if (previous is not None
                and looks_unfinished(previous.text)
                and segment.at - previous.end <= gap_s
                and segment.end - previous.at <= max_span_s):
            merged[-1] = Segment(at=previous.at, end=max(segment.end, previous.end),
                                 text=f"{previous.text.rstrip()} {segment.text.lstrip()}")
            continue
        merged.append(segment)
    return merged

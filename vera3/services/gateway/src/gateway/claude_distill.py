"""Осмысление сессии Claude Code: переписка → выжимка. Что делали, а не как.

Раньше синк лил каждую реплику отдельным событием: одна рабочая сессия давала
сотни событий, набитых кодом и выводом команд. В мозге это шум — искать по нему
нечего, а объём вытесняет полезное. Полезно другое: над чем работали, что
решили, что сломалось и чем кончилось.

Механика свёртки — общая, `vera_shared.llm.fold`. Здесь только то, что
специфично для рабочей сессии: как подписаны роли и о чём спрашивать модель.
"""
from __future__ import annotations

from typing import Any

from vera_shared.llm.fold import FoldSpec, fold

FIELDS = ("summary", "topics", "outline", "decisions",
          "changes", "problems", "open_ends", "numbers")

_PART = """Ты — память Димы. Ниже {scope} одной рабочей сессии с Claude Code.

[Дима] — что просил и говорил Дима.
[Claude] — что отвечал и делал ассистент.

Проект: {project}
Ветка: {branch}

Верни СТРОГО JSON по схеме:
- summary — 2-5 предложений: над чем работали и чем кончилось;
- topics — темы одним-двумя словами (сущности, модули, технологии);
- outline — ход работы по порядку, одна строка на смысловой шаг;
- decisions — что решили: выбранный подход, отвергнутая альтернатива и почему;
- changes — что фактически изменено: файлы, функции, миграции, конфиги;
- problems — что сломалось или не работало, и чем оказалась причина;
- open_ends — что осталось незакрытым, отложено или требует решения Димы;
- numbers — числа, которые что-то значат: версии, объёмы, счётчики, сроки.

Пиши по существу, без кода: имена файлов и функций — да, тела — нет.
Не выдумывай: чего в тексте нет — того нет. Пустой список лучше догадки.

--- {scope} ---
{transcript}"""

_MERGE = """Ты — память Димы. Длинная рабочая сессия осмыслена по частям, части
идут по порядку. Собери из них ОДНУ выжимку того же формата.

Проект: {project}
Ветка: {branch}

Правила сборки:
- summary — про сессию ЦЕЛИКОМ, 3-7 предложений, а не склейка частей;
- outline — общий ход по порядку частей, без повторов;
- остальные списки — объединить и убрать дубли, порядок сохранить;
- поздние части важнее ранних: если подход по ходу сессии переиграли, в итоге
  поздний, но упомяни, что меняли и почему;
- проблема, которую в поздней части починили, остаётся в problems с причиной;
- ничего не додумывай: что не названо ни в одной части, того нет.

--- части ---
{parts}"""

SPEC = FoldSpec(
    name="claude_session",
    fields=FIELDS,
    part_prompt=_PART,
    merge_prompt=_MERGE,
    empty_summary="(сессию не удалось осмыслить — сохранён только факт)",
    # Потолок по замеру, а не на глаз: на 2026-08-26 в ~/.claude/projects
    # 26 живых сессий, самая большая — 681 тыс. символов, это 20 окон.
    # Голосовые 12 окон здесь обрезали бы хвост самой длинной работы.
    max_windows=24,
    # Окна независимы, а ждём мы брокер: тройная параллель сокращает
    # 20-оконную сессию с часов до минут.
    parallel=3,
)

EMPTY = SPEC.empty


def render(turns: list[Any]) -> list[str]:
    """Реплики → строки переписки. Порядок как пришёл, пустые выброшены."""
    lines = []
    for turn in turns:
        text = (turn.text if hasattr(turn, "text") else turn.get("text", "")).strip()
        if not text:
            continue
        role = turn.role if hasattr(turn, "role") else turn.get("role", "user")
        lines.append(f"[{'Дима' if role == 'user' else 'Claude'}] {text}")
    return lines


async def distill(turns: list[Any], *, project: str | None, branch: str | None,
                  poll_deadline_s: float | None = None,
                  ) -> tuple[dict[str, Any], dict[str, Any]]:
    """Переписка → (выжимка, отчёт о работе). Никогда не бросает."""
    return await fold(render(turns), SPEC,
                      {"project": project or "неизвестно", "branch": branch or "нет"},
                      poll_deadline_s=poll_deadline_s)

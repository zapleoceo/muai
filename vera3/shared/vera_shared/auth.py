"""Сравнение внутреннего секрета — одно на все службы.

Проверка `X-Internal-Secret` была написана дважды: в `gateway/auth.py` (чей
докстринг рассказывает, как ДО этого свёл три копии в одну) и заново в
`brain_search/app.py`. Сервисы не импортируют друг друга, поэтому общее
место у них ровно одно — здесь.

Функция намеренно не знает про HTTP: `vera_shared` не зависит от FastAPI, и
не должен. Каждая служба сама решает, во что превратить `False` — обычно в
`HTTPException(401)`.

Fail-closed: секрет не сконфигурирован = доступа нет ни у кого. Обратное
(пустой секрет пропускает всех) держалось на том, что docker-compose требует
переменную; при запуске мимо compose такая служба открылась бы целиком и
молча.
"""
from __future__ import annotations

import hmac


def internal_secret_ok(provided: str | None, expected: str | None) -> bool:
    """Совпадает ли предъявленный секрет с ожидаемым.

    Сравнение постоянное по времени. Обычный `!=` выходит из цикла на первом
    несовпавшем байте, то есть время ответа зависит от длины совпавшего
    префикса. Порты слушают только 127.0.0.1, так что эксплуатировать это
    сквозь сетевой стек Docker тяжело — но правка в одну строку, а рядом, в
    `dashboard/auth.py`, HMAC уже сравнивается через compare_digest.
    """
    if not expected or provided is None:
        return False
    return hmac.compare_digest(provided, expected)

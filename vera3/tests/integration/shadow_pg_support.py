from __future__ import annotations

import os
from contextlib import asynccontextmanager
from pathlib import Path
from uuid import uuid4

import pytest
from sqlalchemy import text
from sqlalchemy.engine import make_url
from sqlalchemy.ext.asyncio import AsyncConnection, create_async_engine


def sample_source(
    revision: str = "1", external_id: str = "42", account: str = "owner-a"
):
    from vera_shared.ingest.shadow_types import SourceRevision

    return SourceRevision(
        provider="telegram",
        account_id=account,
        object_type="message",
        external_id=external_id,
        revision=revision,
        content_hash=f"hash-{revision}-{external_id}",
        received_at=f"2026-10-03T00:00:0{revision}Z",
        required_scope=f"telegram:{account}",
        previous_revision=str(int(revision) - 1) if revision != "1" else None,
    )


